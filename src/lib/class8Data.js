export function formatMaterialTitle(className, subject, chapter, title) {
  const cleanTitle = (title || chapter || 'Notes PDF').trim();
  return `[CLASS:${className}][SUBJECT:${subject}][CHAPTER:${chapter}] ${cleanTitle}`;
}

export function parseMaterialMetadata(m) {
  const title = m.title || '';
  const classMatch = title.match(/\[CLASS:([^\]]+)\]/i);
  const subjectMatch = title.match(/\[SUBJECT:([^\]]+)\]/i);
  const chapterMatch = title.match(/\[CHAPTER:([^\]]+)\]/i);

  const className = classMatch ? classMatch[1].trim() : 'Class 8th';
  const subject = subjectMatch ? subjectMatch[1].trim() : null;
  const chapter = chapterMatch ? chapterMatch[1].trim() : null;
  
  const cleanTitle = title
    .replace(/\[CLASS:[^\]]+\]/gi, '')
    .replace(/\[SUBJECT:[^\]]+\]/gi, '')
    .replace(/\[CHAPTER:[^\]]+\]/gi, '')
    .trim() || title;

  return {
    ...m,
    className,
    subject,
    chapter,
    cleanTitle
  };
}

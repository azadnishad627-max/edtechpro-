// Helper to generate dynamic randomized variations for numerical questions
export function getFallbackQuestionsForSubject(subjectName, count) {
  let pool = fallbackQuestionBank[subjectName] || [];
  if (pool.length === 0) {
    // If exact name not found, try MAT
    pool = fallbackQuestionBank['Mental Ability (MAT)'];
  }

  const result = [];
  const usedTexts = new Set();

  // First copy base questions
  for (const q of pool) {
    if (!usedTexts.has(q.question_text)) {
      usedTexts.add(q.question_text);
      result.push({ ...q });
    }
    if (result.length >= count) break;
  }

  // If still need more to satisfy count (e.g. 50 questions), generate procedural NMMS variations
  let counter = 1;
  while (result.length < count) {
    const base = pool[counter % pool.length];
    const n = counter + 1;
    let varQuestion;

    if (subjectName.includes('Mental Ability') || subjectName.includes('MAT')) {
      const a1 = 3 * n;
      const a2 = 3 * (n + 1);
      const a3 = 3 * (n + 2);
      const a4 = 3 * (n + 3);
      const ans = 3 * (n + 4);
      varQuestion = {
        question_text: `निम्नलिखित संख्या श्रृंखला में अगला पद क्या होगा? ${a1}, ${a2}, ${a3}, ${a4}, ?`,
        option_a: String(ans - 3),
        option_b: String(ans),
        option_c: String(ans + 3),
        option_d: String(ans + 6),
        correct_answer: String(ans)
      };
    } else if (subjectName.includes('Math')) {
      const xVal = (counter % 12) + 2;
      const cVal = (counter % 7) + 3;
      const rhs = 2 * xVal + cVal;
      varQuestion = {
        question_text: `रैखिक समीकरण 2x + ${cVal} = ${rhs} में x का मान ज्ञात कीजिए:`,
        option_a: String(xVal - 1),
        option_b: String(xVal),
        option_c: String(xVal + 1),
        option_d: String(xVal + 2),
        correct_answer: String(xVal)
      };
    } else {
      varQuestion = {
        ...base,
        question_text: `${base.question_text} (प्र. सेट ${counter + 1})`
      };
    }

    if (!usedTexts.has(varQuestion.question_text)) {
      usedTexts.add(varQuestion.question_text);
      result.push(varQuestion);
    }
    counter++;
  }

  return result.slice(0, count);
}